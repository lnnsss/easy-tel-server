const buildPrompt = ({ wordRu, wordTatar, wordEn }) => {
    const ru = capitalizeFirst(wordRu);
    const tat = capitalizeFirst(wordTatar);
    const en = normalizeSpaces(wordEn);

    return [
        `Напиши качественное словарное описание на русском языке для слова "${ru}".`,
        `Татарский эквивалент: "${tat}". Английский ориентир: "${en}".`,
        "Формат: 4-6 предложений, 500-900 символов.",
        `Первое предложение начни строго с шаблона: "${ru} — это ...".`,
        "Пиши естественно, как в хорошем учебном словаре: что это, как выглядит/используется, где встречается, варианты или особенности.",
        "Не упоминай ИИ, источник данных, Kaikki, Wiktionary, перевод, лингвистику, уроки или грамматику.",
        "Верни только итоговый абзац без заголовков и списков."
    ].join(" ");
};

const generateWithAi = async ({ wordRu, wordTatar, wordEn }) => {
    try {
        const response = await sendChatToMl({
            mode: "tutor",
            temperature: 0.7,
            maxNewTokens: 420,
            timeoutMs: AI_TIMEOUT_MS,
            messages: [
                {
                    role: "system",
                    content: "Ты пишешь краткие словарные описания на русском языке. Возвращай только итоговый абзац."
                },
                { role: "user", content: buildPrompt({ wordRu, wordTatar, wordEn }) }
            ]
        });

        return cleanDescription(response.reply);
    } catch (err) {
        console.warn("⚠️ Локальное AI описание недоступно, используем fallback:", err?.message || err);
        return "";
    }
};

export const buildWordTitleCase = (value) => capitalizeFirst(value);

export const resolveRichDescription = async ({ wordId, wordRu, wordTatar, wordEn, existingDescription }) => {
    const cacheKey = String(wordId || `${wordRu}::${wordTatar}::${wordEn}`);
    if (descriptionCache.has(cacheKey)) {
        return descriptionCache.get(cacheKey);
    }

    if (looksLikeRichDescription(existingDescription)) {
        const rich = cleanDescription(existingDescription);
        descriptionCache.set(cacheKey, rich);
        return rich;
    }

    const aiText = await generateWithAi({ wordRu, wordTatar, wordEn });
    const prebuilt = RICH_FALLBACK_BY_EN.get(normalizeKey(wordEn));
    const finalText = looksLikeRichDescription(aiText)
        ? aiText
        : (prebuilt || fallbackDescription({ wordRu, wordTatar }));

    descriptionCache.set(cacheKey, finalText);
    return finalText;
};

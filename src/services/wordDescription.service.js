const descriptionCache = new Map();

const normalizeSpaces = (value) => String(value || "").replace(/\s+/g, " ").trim();
const normalizeKey = (value) => normalizeSpaces(value).toLowerCase();

const capitalizeFirst = (value) => {
    const clean = normalizeSpaces(value);
    if (!clean) return "";
    return clean.charAt(0).toUpperCase() + clean.slice(1);
};

const cleanDescription = (value) => normalizeSpaces(
    String(value || "")
        .replace(/^["'`]+|["'`]+$/g, "")
        .replace(/\s+/g, " ")
);

const looksLikeRichDescription = (value) => {
    const text = cleanDescription(value);
    if (!text) return false;
    if (text.length < 260) return false;
    if (/^слово из открытого словаря/i.test(text)) return false;
    if (/— татарское слово, переводится/i.test(text)) return false;
    return /[.!?]/.test(text);
};

const fallbackDescription = ({ wordRu, wordTatar }) => {
    const ru = capitalizeFirst(wordRu || "Это слово");
    const tat = capitalizeFirst(wordTatar || "");
    return `${ru} — это предмет или понятие, которое часто встречается в повседневной жизни и используется в разных ситуациях. Обычно ${ru.toLowerCase()} имеет понятное практическое назначение и встречается дома, на учебе, на работе или в общественных местах. Это слово удобно запоминать через короткие жизненные примеры, потому что оно часто используется в обычной разговорной речи. Татарский вариант «${tat || ru}» полезно регулярно повторять в простых фразах, чтобы быстрее перевести слово в активный словарь.`;
};

